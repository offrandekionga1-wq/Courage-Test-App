"""Traduction française des amorces standard des guides de conversation Wikivoyage.

Les guides du Wikivoyage anglais reposent sur un gabarit commun : les mêmes phrases d'amorce
(« Hello. », « How much does it cost? »…) reviennent dans chaque langue. Cette table les rend en
français, afin que les cours tirés du Wikivoyage anglais (lituanien, tagalog) soient en français
comme les autres. Les phrases qui ne figurent pas ici restent en anglais et sont marquées.

La clé est normalisée par `norm()` : minuscules, sans ponctuation finale ni parenthèses.
"""
import re

_PAREN = re.compile(r'\([^)]*\)')


def norm(s: str) -> str:
    s = _PAREN.sub(' ', s)
    s = s.replace('’', "'").replace('“', '').replace('”', '')
    s = re.sub(r'\s+', ' ', s).strip().lower()
    return s.rstrip(' .!?:;,')


